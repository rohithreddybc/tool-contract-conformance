def build_open_world_section(name: str, rows: list) -> Optional[dict]:
    if not rows:
        return None
    # Unit of account: one (mutation_seq, tool) pair -- see the final report for why this is the
    # chosen operationalization (a single cosmic-ray mutation can be live for one contracted
    # tool's contract and not another's, when it touches code shared or unrelated to either).
    live_rows = [r for r in rows if r.get("live")]
    n_mutations = len(set(r["mutation_seq"] for r in rows))
    n_live = len(live_rows)

    def is_escape(r: dict) -> bool:
        # sec 4.2: "a behaviourally live mutant that the conformance checker does not report as
        # VIOLATES" -- a checker crash (detected=None) trivially satisfies "did not report
        # VIOLATES" and is counted as an escape, with its own reason code surfaced separately
        # (see reason_codes below) rather than silently dropped from the denominator.
        return r.get("detected") is not True

    escapes = [r for r in live_rows if is_escape(r)]
    n_escapes_raw = len(escapes)

    raw_rate = wilson_interval(n_escapes_raw, n_live) if n_live > 0 else None

    reason_codes = Counter()
    for r in escapes:
        if r.get("detected") is None:
            reason_codes["checker_crashed_or_probe_run_failed"] += 1
        else:
            reason_codes["checker_evaluated_and_did_not_flag"] += 1

    # sec 4.3 decomposition -- mechanical, from `escape_cause` (mutation.score.classify_escape,
    # computed at scoring time; see cr_toy/cr_tau2_real's scoring_lib.py). Escapes where the
    # checker itself crashed (detected=None) have no escape_cause -- classify_escape needs a
    # completed run_contract to compute the clause-gap/probe-gap/canonicalization-gap test, which
    # a crash never produced. These are their own bucket, not folded into probe_gap by default.
    decomposition = Counter()
    ambiguous_for_human_review = []
    for r in escapes:
        cause = r.get("escape_cause")
        if cause is None:
            if r.get("detected") is None:
                decomposition["checker_crashed_uncategorized"] += 1
            else:
                decomposition["classification_error"] += 1
                ambiguous_for_human_review.append(r)
        else:
            decomposition[cause] += 1

    # Adjudication (sec 4.4): rule 2 (volatile field) is exactly what classify_escape's
    # canonicalization_gap bucket already tests mechanically (unmasking flips the verdict).
    # Rule 1 (interface-invisible) and the 20% dual-adjudication requirement both need a HUMAN
    # annotator -- neither is automated here (mutation.score.adjudicate_equivalence's own
    # docstring: rule 1 "is explicitly NOT automated"). So the adjudicated rate below reflects
    # ONLY the mechanical rule-2 reclassification -- a conservative floor on what a human
    # adjudication pass could additionally remove, not the full sec 4.4 adjudicated rate.
    n_adjudicated_equivalent = decomposition.get("canonicalization_gap", 0)
    n_escapes_adjudicated = n_escapes_raw - n_adjudicated_equivalent
    adjudicated_rate = wilson_interval(n_escapes_adjudicated, n_live) if n_live > 0 else None

    per_tool_live = Counter(r["tool"] for r in live_rows)
    per_tool_escape = Counter(r["tool"] for r in escapes)
    per_tool_counts = {t: (per_tool_escape.get(t, 0), n) for t, n in per_tool_live.items() if n > 0}
    per_tool_section = _pooled_and_per_tool(per_tool_counts, f"{name} escape rate")

    return {
        "n_mutations_scored": n_mutations,
        "n_mutation_tool_pairs": len(rows),
        "n_behaviorally_live": n_live,
        "behaviorally_live_fraction_of_pairs": (n_live / len(rows)) if rows else None,
        "escape_rate_raw": _rate_dict(raw_rate, f"{name} escape rate (raw)") if raw_rate else None,
        "escape_rate_adjudicated": _rate_dict(adjudicated_rate, f"{name} escape rate (adjudicated, rule-2 only)") if adjudicated_rate else None,
        "n_escapes_raw": n_escapes_raw,
        "n_escapes_adjudicated": n_escapes_adjudicated,
        "n_reclassified_equivalent_by_rule2": n_adjudicated_equivalent,
        "escape_reason_codes": dict(reason_codes),
        "escape_decomposition": dict(decomposition),
        "per_tool": per_tool_section,
        "ambiguous_flagged_for_human_review": ambiguous_for_human_review,
        "adjudication_note": (
            "Only mechanical rule 2 (declared-volatile field) applied. Rule 1 "
            "(interface-invisible) and the pre-registered 20% second-annotator dual-adjudication "
            "sample both require a human annotator and were NOT performed in this automated run -- "
            "flagged here rather than silently assumed. The adjudicated rate above is therefore a "
            "conservative one: a human pass could remove more escapes via rule 1, never fewer."
        ),
    }


