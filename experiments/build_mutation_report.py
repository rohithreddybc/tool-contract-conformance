def main() -> int:
    closed_rows = load_jsonl(CLOSED_WORLD_RAW)
    if not closed_rows:
        print(f"WARNING: {CLOSED_WORLD_RAW} is empty or missing -- closed-world section will be empty")

    header = next((r for r in closed_rows if r.get("kind") == "run_header"), {})

    result: dict = {
        "provenance": {
            "git_commit": git_commit(),
            "generated_by": "experiments/build_mutation_report.py",
            "closed_world_seed": header.get("seed"),
            "closed_world_source": str(CLOSED_WORLD_RAW),
        },
        "closed_world": {
            "recall": build_closed_world_recall(closed_rows),
            "precision": build_precision(closed_rows),
            "n_targets": header.get("n_targets"),
            "adapter_availability_notes": header.get("notes"),
        },
        "open_world": {},
        "contract_coverage": build_coverage_section(),
    }

    for name, path in OPEN_WORLD_RAW.items():
        rows = load_jsonl(path)
        if rows:
            result["open_world"][name] = build_open_world_section(name, rows)
        else:
            result["open_world"][name] = {"status": "no data", "path": str(path)}

    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    with open(OUT_JSON, "w", encoding="utf-8") as fh:
        json.dump(result, fh, indent=2, sort_keys=True, default=str)
    print(f"wrote {OUT_JSON}")

    write_markdown_summary(result)
    print(f"wrote {OUT_MD}")
    return 0


def _fmt_rate(section: Optional[dict], key: str = "pooled") -> str:
    if not section or key not in section:
        return "no data"
    r = section[key]
    return f"{r['claim']}"


def write_markdown_summary(result: dict) -> None:
    lines = []
    lines.append("# Mutation Validation Report\n")
    lines.append(f"Generated by `experiments/build_mutation_report.py` at commit `{result['provenance']['git_commit']}`.\n")
    lines.append(
        "Framing fixed by `experiments/detector_analysis_plan.md` sec 7, restated here so it is "
        "never renegotiated after seeing numbers: closed-world recall means \"detects violations "
        "of the clauses we authored,\" never \"detects tool-contract defects.\" The open-world "
        "escape rate is a lower bound on the taxonomy's incompleteness, never evidence of "
        "coverage or completeness. No hypothesis tests, no p-values, appear anywhere below.\n"
    )

    lines.append("## Closed-world arm\n")
    lines.append(f"{result['closed_world'].get('n_targets')} eligible targets. See `mutation_scores.json` for the full breakdown.\n")
    lines.append(
        "**Headline recall is real-tools-only** (tau2-bench + AgentDojo + MM-ToolSandbox). The "
        "toy domain was authored by the checker's own authors with this taxonomy in mind; pooling "
        "it into the headline would flatter the detector. Toy-domain numbers are reported "
        "immediately below each headline row as a debug/sanity reference, never as evidence.\n"
    )
    rec = result["closed_world"]["recall"]
    lines.append("### Headline recall (real tools only)\n")
    lines.append("| Operator | Recall (Wilson lower bound) | n drawn | detected | missed | untestable | error |")
    lines.append("|---|---|---|---|---|---|---|")
    for op in DEFECT_OPERATORS:
        entry = rec["by_operator"].get(op, {})
        if entry.get("status") == "UNTESTABLE_STRUCTURAL":
            lines.append(f"| {op} | UNTESTABLE (no checker path) | {entry['n_drawn']} | 0 | 0 | {entry['n_drawn']} | 0 |")
            continue
        s = entry.get("real", {})
        cc = s.get("classification_counts", {})
        recall_str = _fmt_rate(s.get("recall")) if s.get("recall") else "no data"
        lines.append(
            f"| {op} | {recall_str} | {s.get('n_drawn', 0)} | {cc.get('detected', 0)} | "
            f"{cc.get('missed', 0)} | {cc.get('untestable_no_clause_evaluated', 0)} | {cc.get('error', 0)} |"
        )
    lines.append("")

    lines.append("### Toy-domain recall (debug reference, NOT headline)\n")
    lines.append("| Operator | Recall (Wilson lower bound) | n drawn | detected | missed | untestable | error |")
    lines.append("|---|---|---|---|---|---|---|")
    for op in DEFECT_OPERATORS:
        entry = rec["by_operator"].get(op, {})
        if entry.get("status") == "UNTESTABLE_STRUCTURAL":
            continue
        s = entry.get("toy", {})
        cc = s.get("classification_counts", {})
        recall_str = _fmt_rate(s.get("recall")) if s.get("recall") else "no data"
        lines.append(
            f"| {op} | {recall_str} | {s.get('n_drawn', 0)} | {cc.get('detected', 0)} | "
            f"{cc.get('missed', 0)} | {cc.get('untestable_no_clause_evaluated', 0)} | {cc.get('error', 0)} |"
        )
    lines.append("")

    prec = result["closed_world"]["precision"]
    lines.append(f"**Precision (real-world detects/all flags, toy+real pooled):** {_fmt_rate(prec['precision'])}" if prec.get("precision") else "**Precision:** no data")
    lines.append(f"TP={prec['tp']}, FP={prec['fp']}, n_flags={prec['n_flags']}, equivalence controls scored={prec['n_equivalence_controls_scored']}\n")

    lines.append("## Open-world arm (cosmic-ray)\n")
    for name, section in result["open_world"].items():
        lines.append(f"### {name}\n")
        if section.get("status") == "no data":
            lines.append(f"No data at `{section['path']}`.\n")
            continue
        lines.append(f"- Mutations scored: {section['n_mutations_scored']}")
        lines.append(f"- (mutation, tool) pairs: {section['n_mutation_tool_pairs']}")
        lines.append(f"- Behaviorally live: {section['n_behaviorally_live']} ({section['behaviorally_live_fraction_of_pairs']:.3%} of pairs)" if section['behaviorally_live_fraction_of_pairs'] is not None else "- Behaviorally live: n/a")
        if section.get("escape_rate_raw"):
            lines.append(f"- Escape rate (raw): {section['escape_rate_raw']['claim']}")
            lines.append(f"- Escape rate (adjudicated, rule-2 only): {section['escape_rate_adjudicated']['claim']}")
            lines.append(f"- Gap (raw n={section['n_escapes_raw']} vs adjudicated n={section['n_escapes_adjudicated']}): {section['n_reclassified_equivalent_by_rule2']} escapes reclassified equivalent by mechanical rule 2")
            lines.append(f"- Escape decomposition: {section['escape_decomposition']}")
            lines.append(f"- Escape reason codes: {section['escape_reason_codes']}")
            lines.append(f"- {section['adjudication_note']}")
            if section["ambiguous_flagged_for_human_review"]:
                lines.append(f"- **{len(section['ambiguous_flagged_for_human_review'])} escapes flagged for human adjudication** (classification_error bucket) -- see mutation_scores.json")
        else:
            lines.append("- No behaviorally live mutants observed -- escape rate undefined (denominator 0). See the caveat below.")
        lines.append("")

    lines.append("## Contract coverage (sec 6)\n")
    lines.append("| Benchmark | n contracts | mean sentence-operationalized fraction | mean state-write-covered fraction | biconditional:true adopted |")
    lines.append("|---|---|---|---|---|")
    for benchmark, cov in result["contract_coverage"].items():
        sf = cov["mean_sentence_operationalized_fraction"]
        sw = cov["mean_state_write_covered_fraction"]
        lines.append(
            f"| {benchmark} | {cov['n_contracts']} | {f'{sf:.3f}' if sf is not None else 'n/a'} | "
            f"{f'{sw:.3f}' if sw is not None else 'n/a'} | {cov['biconditional_true_adopted']}/{cov['n_contracts']} |"
        )
    lines.append("")

    OUT_MD.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    sys.exit(main())
