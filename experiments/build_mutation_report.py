# Closed-world arm
# =================================================================================================


def classify_defect_mutant(row: dict) -> str:
    """One of: detected | missed | untestable_no_clause_evaluated | untestable_no_checker_path |
    error. `detected`/`missed` both mean the checker evaluated at least one testable clause
    (CONFORMS and/or VIOLATES present); `untestable_no_clause_evaluated` means every row the
    checker produced for this mutant was UNTESTABLE (a probe-gap-at-corpus-level situation, not
    a genuine "the checker looked and missed"); `untestable_no_checker_path` is M-RESET's
    structural case (see experiments/run_mutation_closed_world.py's run_reset_operator
    docstring: no dynamic reset-clause evaluator exists in the wired checker at all);
    `error` is a patch/build/invoke crash unrelated to any of the above."""
    err = row.get("error")
    if err and isinstance(err, str) and err.startswith("UNTESTABLE:"):
        return "untestable_no_checker_path"
    if row.get("detected") is None:
        return "error"
    vc = row.get("verdict_counts") or {}
    if vc.get("VIOLATES", 0) > 0:
        return "detected"
    if vc.get("CONFORMS", 0) > 0:
        return "missed"
    return "untestable_no_clause_evaluated"


def _rate_dict(rate: Rate, label: str) -> dict:
    return {
        "label": label, "successes": rate.successes, "n": rate.n, "point": rate.point,
        "wilson_lower": rate.lower, "wilson_upper": rate.upper, "claim": rate.claim(label),
    }


def _pooled_and_per_tool(per_tool_counts: "dict[str, tuple]", label: str) -> Optional[dict]:
    per_tool_counts = {t: c for t, c in per_tool_counts.items() if c[1] > 0}
    if not per_tool_counts:
        return None
    per_tool_rates = {t: _rate_dict(wilson_interval(x, n), f"{label}:{t}") for t, (x, n) in per_tool_counts.items()}
    pooled = tool_clustered_wilson(per_tool_counts)
    return {"pooled": _rate_dict(pooled, label), "per_tool": per_tool_rates, "n_tools": len(per_tool_counts)}


def build_closed_world_recall(rows: list) -> dict:
    defects = [r for r in rows if r.get("kind") == "defect_mutant"]
    out: dict = {"by_operator": {}, "pool_sizes": {}}

    pool_rows = [r for r in rows if r.get("kind") == "operator_pool_size"]
    for r in pool_rows:
        out["pool_sizes"][r["operator"]] = {"pool_size": r["pool_size"], "drawn": r["drawn"], "requested": r["requested"]}

    for operator in DEFECT_OPERATORS:
        op_rows = [r for r in defects if r["operator"] == operator]
        classified = [(r, classify_defect_mutant(r)) for r in op_rows]
        counts = Counter(c for _, c in classified)

        if operator == "M-RESET":
            out["by_operator"][operator] = {
                "status": "UNTESTABLE_STRUCTURAL",
                "reason": "no_reset_path_checker: dynamic.harness.run_contract never calls Adapter.reset() "
                          "or evaluates a contract's reset: clause -- confirmed by inspection, not assumed. "
                          "Every M-RESET mutant is therefore UNTESTABLE by the currently-wired checker, "
                          "structurally, not empirically -- reporting a Wilson interval on 0/N here would "
                          "misrepresent 'the checker never had a code path to try' as 'the checker tried and "
                          "missed every time'.",
                "n_drawn": len(op_rows), "classification_counts": dict(counts),
                "toy_n": sum(1 for r in op_rows if r["is_toy"]), "real_n": sum(1 for r in op_rows if not r["is_toy"]),
            }
            continue

        for scope, pred in (("toy", lambda r: r["is_toy"]), ("real", lambda r: not r["is_toy"]), ("all", lambda r: True)):
            scoped = [r for r in op_rows if pred(r)]
            per_tool: "dict[str, list]" = defaultdict(lambda: [0, 0])
            for r in scoped:
                cls = classify_defect_mutant(r)
                per_tool[r["tool"]][1] += 1
                if cls == "detected":
                    per_tool[r["tool"]][0] += 1
            per_tool_counts = {t: (x, n) for t, (x, n) in per_tool.items()}
            section = _pooled_and_per_tool(per_tool_counts, f"{operator} recall ({scope})")
            scoped_classified = Counter(classify_defect_mutant(r) for r in scoped)
            out["by_operator"].setdefault(operator, {})[scope] = {
                "recall": section, "n_drawn": len(scoped), "classification_counts": dict(scoped_classified),
            }
    return out


def build_precision(rows: list) -> dict:
    defects = [r for r in rows if r.get("kind") == "defect_mutant" and r["operator"] != "M-RESET"]
    equivalents = [r for r in rows if r.get("kind") == "equivalence_mutant"]

    per_tool: "dict[str, list]" = defaultdict(lambda: [0, 0])  # tool -> [TP+FP flags issued correctly? see below]
    tp = 0
    fp = 0
    fp_rows = []
    for r in defects:
        if classify_defect_mutant(r) == "detected":
            tp += 1
            per_tool[r["tool"]][0] += 1
            per_tool[r["tool"]][1] += 1
        elif r.get("detected") is False:
            per_tool[r["tool"]][1] += 1  # a non-flag on a defect mutant contributes to neither TP nor FP
    for r in equivalents:
        if r.get("detected") is True:
            fp += 1
            per_tool[r["tool"]][1] += 1
            fp_rows.append(r)
        elif r.get("detected") is False:
            per_tool[r["tool"]][1] += 1

    # Precision's denominator is flags issued (TP+FP), not every mutant scored -- rebuild
    # per-tool counts restricted to (successes=TP_i, n=TP_i+FP_i), dropping tools with zero flags
    # (precision is undefined there, not zero).
    per_tool_flags: "dict[str, list]" = defaultdict(lambda: [0, 0])
    for r in defects:
        if classify_defect_mutant(r) == "detected":
            per_tool_flags[r["tool"]][0] += 1
            per_tool_flags[r["tool"]][1] += 1
    for r in equivalents:
        if r.get("detected") is True:
            per_tool_flags[r["tool"]][1] += 1

    per_tool_counts = {t: (x, n) for t, (x, n) in per_tool_flags.items() if n > 0}
    section = _pooled_and_per_tool(per_tool_counts, "precision")
    return {
        "precision": section, "tp": tp, "fp": fp, "n_flags": tp + fp,
        "false_positive_mutants": [{"tool": r["tool"], "equivalence_kind": r["equivalence_kind"]} for r in fp_rows],
        "n_equivalence_controls_scored": len(equivalents),
    }


