#!/usr/bin/env python
"""Statistics and reporting for BOTH mutation-validation arms --
experiments/detector_analysis_plan.md sec 5-7. This script computes nothing that isn't specified
there: Wilson intervals (mutation.score.wilson_interval), the design-effect-adjusted pooled
interval (mutation.score.tool_clustered_wilson), toy-vs-real and per-tool breakdowns, precision,
raw/adjudicated escape rate, and the sec 4.3 clause/probe/canonicalization decomposition.

Consumes (never writes to) report/mutation_closed_world_raw.jsonl (produced by
experiments/run_mutation_closed_world.py) and report/mutation_open_world_{toy,tau2}_raw.jsonl
(produced by the cosmic-ray runs -- see report/mutation_open_world_provenance.md for how those
were generated and why they are copied in rather than generated by this repo's own test command).

Output: report/mutation_scores.json (machine-readable) and report/mutation_summary.md
(human-readable), matching CLAUDE.md's "generated artifacts are generated only" rule applied to
this experiment's own outputs.

NO HYPOTHESIS TESTS. NO P-VALUES. Every claim in the human-readable summary is stated at the
Wilson lower bound (mutation.score.Rate.claim()), never the point estimate, per sec 5.
"""
from __future__ import annotations

import json
import subprocess
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any, Optional

PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from mutation.score import Rate, tool_clustered_wilson, wilson_interval  # noqa: E402

REPORT_DIR = PROJECT_ROOT / "report"
CLOSED_WORLD_RAW = REPORT_DIR / "mutation_closed_world_raw.jsonl"
OPEN_WORLD_RAW = {
    "toy": REPORT_DIR / "mutation_open_world_toy_raw.jsonl",
    "tau2-telecom": REPORT_DIR / "mutation_open_world_tau2_raw.jsonl",
}
OUT_JSON = REPORT_DIR / "mutation_scores.json"
OUT_MD = REPORT_DIR / "mutation_summary.md"

DEFECT_OPERATORS = ("M-PHANTOM", "M-PRECOND", "M-IGNARG", "M-PARTIAL", "M-INVAR", "M-RESET")


def load_jsonl(path: Path) -> list:
    if not path.exists():
        return []
    with open(path, "r", encoding="utf-8") as fh:
        return [json.loads(line) for line in fh if line.strip()]


def git_commit() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=PROJECT_ROOT, text=True).strip()
    except Exception:  # noqa: BLE001
        return "unknown"


