# Contract coverage (sec 6) -- reads spec/coverage.py's own JSON output, computed separately
# (spec/coverage.py <contracts glob> --repo-root <repo> --json), never recomputed here.
# =================================================================================================


def build_coverage_section() -> dict:
    import glob as globmod

    from spec.coverage import coverage_report

    repo_root_by_benchmark = {
        "toy": (PROJECT_ROOT, "spec/contracts/toy/*.yaml"),
        "tau2-bench": (PROJECT_ROOT / "repos" / "tau2", "spec/contracts/tau2/*.yaml"),
        "agentdojo": (PROJECT_ROOT / "repos" / "agentdojo", "spec/contracts/agentdojo/*.yaml"),
        "mm-toolsandbox": (PROJECT_ROOT / "repos" / "mmtoolsandbox", "spec/contracts/mmtoolsandbox/*.yaml"),
    }
    out = {}
    for benchmark, (repo_root, pattern) in repo_root_by_benchmark.items():
        reports = []
        for path in sorted(globmod.glob(str(PROJECT_ROOT / pattern))):
            try:
                reports.append(coverage_report(path, str(repo_root)))
            except Exception as e:  # noqa: BLE001
                reports.append({"contract": path, "error": f"{type(e).__name__}: {e}"})
        sent = [r["sentence"]["sentence_fraction"] for r in reports if "sentence" in r and r["sentence"]["sentence_fraction"] is not None]
        sw = [r["state_write"]["state_write_fraction"] for r in reports if "state_write" in r and r["state_write"]["state_write_fraction"] is not None]
        n_bicond = sum(1 for r in reports if "biconditional" in r and r["biconditional"]["biconditional"])
        out[benchmark] = {
            "n_contracts": len(reports),
            "mean_sentence_operationalized_fraction": (sum(sent) / len(sent)) if sent else None,
            "n_with_sentence_data": len(sent),
            "mean_state_write_covered_fraction": (sum(sw) / len(sw)) if sw else None,
            "n_with_state_write_data": len(sw),
            "biconditional_true_adopted": n_bicond,
            "reports": reports,
        }
    return out


