"""The dynamic harness -- ARCHITECTURE-FINAL.md sec 1/7 ("dynamic/harness.py"): the
snapshot -> invoke -> snapshot -> evaluate loop over a live `adapters.base.Adapter`, driven by
`dynamic/probes.py`'s probe plan, producing `core.verdict.ClauseVerdict`s and writing
`report/findings.jsonl` (deliverable 6, the machine-readable conformance report format).

This module owns exactly one new piece of checker logic beyond what `adapters/contract_check.py`
already provides: `check_ignored_argument`, implementing the REVISED M-IGNARG definition (CLAUDE.md
build spec). It could not live in `adapters/contract_check.py`, whose two entry points both grade
a single (pre, post, args, result) tuple; Ignored Argument is decided across MULTIPLE calls that
vary one argument, so it belongs with the multi-invocation loop that produces those calls.

THE DEFINITION CHANGE, AND WHY. The old (pre-registration-era) rule required BOTH the post-state
AND the result to be invariant across an argument's varied values before reporting Ignored
Argument -- a conjunctive test. That rule cannot fire on FINDINGS-VERIFIED.md Finding 6:
AgentDojo's `reserve_car_rental` discards `end_time` from state (`reservation.end_time =
datetime.fromisoformat(start_time)`, never `end_time`) but ECHOES the caller's `end_time` verbatim
into its success string ("...has been made successfully." built from the local `end_time`
variable, not from state). Under the conjunctive rule, the varying RESULT blocks the verdict on
one of the taxonomy's own anchor findings -- the state genuinely doesn't depend on the argument,
which is exactly what "ignored" means, and the old rule refused to say so.

The new rule: Ignored Argument is decided on POST-STATE INVARIANCE ALONE. Whether the result also
disagrees with state is computed separately and reported as an AGGRAVATING SIGNAL alongside the
finding -- present in every `findings.jsonl` row this module writes for an `arg.*` clause id, never
folded into the verdict itself. See `check_ignored_argument` below.
"""
