# =================================================================================================
# The snapshot/invoke/snapshot primitive, used by every probe kind below.
# =================================================================================================


class InvokeRecord:
    """One fresh-env probe call and everything the checker needs from it: the pre/post snapshots,
    the args, the canonicalized `result` binding (see `adapters.contract_check.to_result_binding`),
    whether the call succeeded, and the raw adapter error string when it did not."""

    __slots__ = ("args", "pre", "post", "result", "success", "error")

    def __init__(self, args: dict, pre: Any, post: Any, result: Any, success: bool, error: Optional[str]):
        self.args = args
        self.pre = pre
        self.post = post
        self.result = result
        self.success = success
        self.error = error


def _invoke_fresh(adapter: Adapter, scenario_id: str, tool: str, args: dict) -> InvokeRecord:
    """fresh_env -> snapshot -> invoke -> snapshot, in a brand-new environment instance every
    time. Each probe call is graded against its OWN fresh pre-snapshot rather than a shared,
    possibly-drifted one -- the same pattern tests/test_tau2_adapter.py's Gate 1a/1b tests use by
    hand, generalised here so the harness never has to reason about accumulated state from an
    earlier probe in the same run."""
    env = adapter.fresh_env(scenario_id)
    pre = adapter.snapshot(env)
    tr: ToolResult = adapter.invoke(env, tool, args)
    post = adapter.snapshot(env)
    result = to_result_binding(tr.raw, tr.success, tr.error)
    return InvokeRecord(args=args, pre=pre, post=post, result=result, success=tr.success, error=tr.error)


# =================================================================================================
# check_ignored_argument -- the one new piece of checker logic this milestone adds.
# =================================================================================================


def check_ignored_argument(
    arg_name: str,
    calls: list,
    *,
    cfg: Optional[CanonicalConfig] = None,
) -> tuple:
    """M-IGNARG under the revised definition (see module docstring): Ignored Argument iff the
    canonicalized post-state is IDENTICAL across every successful call in `calls` despite each
    call using a different value of `arg_name`, all other arguments held fixed. `calls` is a list
    of `InvokeRecord`s that differ only in `arg_name`'s value (dynamic/probes.py's
    `generate_ignored_argument_probes` builds exactly this shape).

    Returns `(ClauseVerdict, aggravation)`. `aggravation` is a plain dict, never folded into the
    ClauseVerdict itself (core/verdict.py's lattice is deliberately not extended for this -- the
    aggravating signal is call-set-level evidence, reported alongside a finding in
    findings.jsonl, not a property of the clause verdict lattice):

        {"aggravating_signal": "result_disagrees_with_state" | None,
         "n_successful_variants": int,
         "argument_values_tried": [...]}   # only populated on a VIOLATES verdict

    Needs at least two SUCCESSFUL calls using at least two DISTINCT values of `arg_name` to say
    anything -- a call that raised never reaches the tool's effect code, so its post-state
    trivially equals pre regardless of what `arg_name` was, and admitting a failed call into the
    comparison would manufacture an Ignored Argument verdict out of an argument that in fact
    determined success or failure (the opposite of ignored). Fewer than two such calls ->
    UNTESTABLE / no_observable_state.
    """
    clause_id = f"arg.{arg_name}"
    cfg = cfg or CanonicalConfig()

    successful = [c for c in calls if c.success]
    seen_values: list = []
    distinct: list = []
    for c in successful:
        v = c.args[arg_name]
        if v in seen_values:
            continue
        seen_values.append(v)
        distinct.append(c)

    if len(distinct) < 2:
        verdict = ClauseVerdict(verdict=Verdict.UNTESTABLE, clause_id=clause_id, reason_code="no_observable_state")
        return verdict, {"aggravating_signal": None, "n_successful_variants": len(distinct)}

    reference = distinct[0]
    state_invariant = all(canonical_equal(reference.post, c.post, cfg) for c in distinct[1:])

    if not state_invariant:
        verdict = ClauseVerdict(verdict=Verdict.CONFORMS, clause_id=clause_id)
        return verdict, {"aggravating_signal": None, "n_successful_variants": len(distinct)}

    # Post-state does not depend on arg_name across every successful variant tried: Ignored
    # Argument, decided on state alone. The aggravating signal is a SEPARATE question, asked only
    # now: does the RESULT vary even though state does not? FINDINGS-VERIFIED.md Finding 6's
    # exact shape (state pinned to start_time, the return string still echoes the discarded
    # end_time) is `result_disagrees_with_state` here.
    result_disagrees = not all(canonical_equal(reference.result, c.result, cfg) for c in distinct[1:])

    verdict = ClauseVerdict(
        verdict=Verdict.VIOLATES,
        clause_id=clause_id,
        defect_class=DefectClass.IGNORED_ARGUMENT,
        witness=Witness(
            args=dict(reference.args),
            diff=diff(reference.pre, reference.post, cfg),
            result=reference.result,
        ),
    )
    aggravation = {
        "aggravating_signal": "result_disagrees_with_state" if result_disagrees else None,
        "n_successful_variants": len(distinct),
        "argument_values_tried": [c.args[arg_name] for c in distinct],
    }
    return verdict, aggravation


