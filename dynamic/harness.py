# The snapshot/invoke/snapshot primitive, used by every probe kind below.
# =================================================================================================


class InvokeRecord:
    """One fresh-env probe call and everything the checker needs from it: the pre/post snapshots,
    the args, the canonicalized `result` binding (see `adapters.contract_check.to_result_binding`),
    whether the call succeeded, and the raw adapter error string when it did not."""

    __slots__ = ("args", "pre", "post", "result", "success", "error")

    def __init__(self, args: dict, pre: Any, post: Any, result: Any, success: bool, error: Optional[str]):
        self.args = args
        self.pre = pre
        self.post = post
        self.result = result
        self.success = success
        self.error = error


def _invoke_fresh(adapter: Adapter, scenario_id: str, tool: str, args: dict) -> InvokeRecord:
    """fresh_env -> snapshot -> invoke -> snapshot, in a brand-new environment instance every
    time. Each probe call is graded against its OWN fresh pre-snapshot rather than a shared,
    possibly-drifted one -- the same pattern tests/test_tau2_adapter.py's Gate 1a/1b tests use by
    hand, generalised here so the harness never has to reason about accumulated state from an
    earlier probe in the same run."""
    env = adapter.fresh_env(scenario_id)
    pre = adapter.snapshot(env)
    tr: ToolResult = adapter.invoke(env, tool, args)
    post = adapter.snapshot(env)
    result = to_result_binding(tr.raw, tr.success, tr.error)
    return InvokeRecord(args=args, pre=pre, post=post, result=result, success=tr.success, error=tr.error)


