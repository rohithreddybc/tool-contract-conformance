def _witness_to_json(w: Optional[Witness]) -> Optional[dict]:
    if w is None:
        return None
    return {"args": w.args, "diff": w.diff, "result": w.result}


def _row(*, kind: str, contract: Contract, scenario_id: str, cv: ClauseVerdict, probe_origin: str, extra: Optional[dict] = None) -> dict:
    row = {
        "kind": kind,
        "benchmark": contract.benchmark,
        "tool": contract.tool,
        "commit": contract.commit,
        "scenario_id": scenario_id,
        "clause_id": cv.clause_id,
        "verdict": cv.verdict.value,
        "defect_class": cv.defect_class.value if cv.defect_class else None,
        "reason_code": cv.reason_code,
        "witness": _witness_to_json(cv.witness),
        "probe_origin": probe_origin,
    }
    if extra:
        row.update(extra)
    return row


def run_contract(
    adapter: Adapter,
    contract: Contract,
    scenario_id: str,
    *,
    cfg: Optional[CanonicalConfig] = None,
    seed: int = 0,
) -> list:
    """The full milestone-2 build-spec loop for one contract against one live adapter: generate
    the probe plan from a fresh pre-snapshot, invoke every probe against its OWN fresh
    environment, evaluate every resulting call against the contract with
    `adapters.contract_check` (effects, precondition enforcement) plus this module's own
    `check_ignored_argument`, and return the `findings.jsonl` rows (see `_row`). Never raises on
    a probe-generation gap -- an effect clause with no happy-path probe, or an argument with too
    few distinct successful variants, is reported as an UNTESTABLE row rather than silently
    dropped, so the sec-4.3 probe-gap accounting in `detector_analysis_plan.md` has something to
    count."""
    cfg = cfg or CanonicalConfig()
    seed_env = adapter.fresh_env(scenario_id)
    pre0 = adapter.snapshot(seed_env)
    plan = build_dynamic_probe_plan(contract, pre0, seed=seed)

    rows: list = []

    # -- preconditions: satisfy probes feed check_effects (more observations of the effect
    #    clauses, each tagged by the precondition-satisfying probe that drove it); violate probes
    #    feed check_precondition_enforcement. --------------------------------------------------
    #
    #    A "satisfy" probe only guarantees ONE clause holds -- it says nothing about the tool's
    #    OTHER declared preconditions, which the same call may still violate. A call that raised
    #    never reached the tool's effect code, so post == pre; running check_effects on that pair
    #    would grade every effect predicate against a no-op and manufacture a false VIOLATES
    #    (typically Phantom Effect, since every effect clause fails identically) out of a tool
    #    that never had a chance to apply them. check_effects is therefore only ever called on a
    #    call that actually succeeded -- a failed satisfy-probe call contributes nothing here (the
    #    happy-path probe below is the real, joint-satisfying source of effect coverage).
    for probe in plan.precondition_probes:
        rec = _invoke_fresh(adapter, scenario_id, contract.tool, probe.args)
        if probe.origin.startswith("precondition_satisfy:"):
            if rec.success:
                for cv in check_effects(contract, rec.pre, rec.post, rec.args, rec.result, cfg=cfg):
                    rows.append(_row(kind="effect", contract=contract, scenario_id=scenario_id, cv=cv, probe_origin=probe.origin))
        elif probe.origin.startswith("precondition_violate:"):
            cv = check_precondition_enforcement(contract, rec.pre, rec.post, rec.args, rec.result, rec.error, cfg=cfg)
            if cv is not None:
                rows.append(_row(kind="precondition_enforcement", contract=contract, scenario_id=scenario_id, cv=cv, probe_origin=probe.origin))

    # -- effects: the happy-path probe. Guarded the same way -- the probe was BUILT to satisfy
    #    every precondition against the contract's own predicates, but the contract's predicates
    #    are a translation of the real implementation's guards and can diverge from them (that
    #    divergence is itself something worth surfacing, not papering over with a false VIOLATES
    #    on every effect clause). ---------------------------------------------------------------
    if plan.effect_probe is not None:
        rec = _invoke_fresh(adapter, scenario_id, contract.tool, plan.effect_probe.args)
        if rec.success:
            for cv in check_effects(contract, rec.pre, rec.post, rec.args, rec.result, cfg=cfg):
                rows.append(_row(kind="effect", contract=contract, scenario_id=scenario_id, cv=cv, probe_origin=plan.effect_probe.origin))
        else:
            for ec in contract.effects:
                cv = ClauseVerdict(verdict=Verdict.UNTESTABLE, clause_id=ec.id, reason_code="no_observable_state")
                rows.append(
                    _row(
                        kind="effect", contract=contract, scenario_id=scenario_id, cv=cv,
                        probe_origin="effect_happy_path_call_failed", extra={"call_error": rec.error},
                    )
                )
    else:
        # A probe gap, not a clause gap: every effect clause covers real behaviour, but this
        # module's own search never found a joint argument assignment satisfying every
        # precondition. Reported per clause so it is countable.
        for ec in contract.effects:
            cv = ClauseVerdict(verdict=Verdict.UNTESTABLE, clause_id=ec.id, reason_code="no_observable_state")
            rows.append(_row(kind="effect", contract=contract, scenario_id=scenario_id, cv=cv, probe_origin="effect_happy_path_not_found"))

    # -- Ignored Argument: one check_ignored_argument call per effective argument that got a
    #    usable variant set. --------------------------------------------------------------------
    covered_args = set()
    for arg_name, variant_probes in plan.ignored_argument_probes.items():
        covered_args.add(arg_name)
        calls = [_invoke_fresh(adapter, scenario_id, contract.tool, p.args) for p in variant_probes]
        cv, aggravation = check_ignored_argument(arg_name, calls, cfg=cfg)
        rows.append(
            _row(
                kind="ignored_argument",
                contract=contract,
                scenario_id=scenario_id,
                cv=cv,
                probe_origin=f"ignored_argument:{arg_name}",
                extra=aggravation,
            )
        )
    for arg_name, spec in contract.signature.args.items():
        if spec.effective and arg_name not in covered_args:
            cv = ClauseVerdict(verdict=Verdict.UNTESTABLE, clause_id=f"arg.{arg_name}", reason_code="no_observable_state")
            rows.append(
                _row(
                    kind="ignored_argument",
                    contract=contract,
                    scenario_id=scenario_id,
                    cv=cv,
                    probe_origin="ignored_argument_probe_not_found",
                    extra={"aggravating_signal": None, "n_successful_variants": 0},
                )
            )

    return rows


# =================================================================================================
# End-to-end runner: toy (all shipped contracts) + tau2 (the two shipped contracts).
# =================================================================================================


def _iter_toy_contracts():
    for path in sorted((CONTRACTS_ROOT / "toy").glob("*.yaml")):
        yield Contract.from_yaml(path), "default"


def _iter_tau2_contracts():
    for path in sorted((CONTRACTS_ROOT / "tau2").glob("*.yaml")):
        if path.suffix != ".yaml":
            continue
        contract = Contract.from_yaml(path)
        domain = TAU2_DOMAIN_BY_TOOL.get(contract.tool)
        if domain is None:
            continue  # not a tool this milestone has a domain mapping for -- skip, don't guess
        yield contract, domain


def run_all(*, seed: int = 0) -> list:
    """Run every shipped toy contract against `ToyAdapter` and every mapped tau2 contract against
    `Tau2Adapter`, returning the combined `findings.jsonl` rows. If the tau2 venv is not
    provisioned, records one `adapter_unavailable` row instead of failing the whole run -- mirrors
    `tests/test_tau2_adapter.py`'s skip discipline, but as data rather than a test skip, since this
    is meant to run outside `unittest` too."""
    rows: list = []

    toy_adapter = ToyAdapter()
    for contract, scenario_id in _iter_toy_contracts():
        rows.extend(run_contract(toy_adapter, contract, scenario_id, cfg=TOY_CANONICAL_CONFIG, seed=seed))

    try:
        tau2_adapter = Tau2Adapter()
    except Tau2AdapterError as e:
        rows.append({"kind": "adapter_unavailable", "benchmark": "tau2-bench", "detail": str(e)})
        return rows
    try:
        for contract, domain in _iter_tau2_contracts():
            rows.extend(run_contract(tau2_adapter, contract, domain, seed=seed))
    finally:
        tau2_adapter.close()

    return rows


def write_findings(rows: list, out_path: Path = REPORT_PATH) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fh:
        for row in rows:
            fh.write(json.dumps(row, sort_keys=True) + "\n")


def main(argv: Optional[list] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=REPORT_PATH, help="output JSONL path")
    parser.add_argument("--seed", type=int, default=0, help="probe-plan search seed")
    args = parser.parse_args(argv)

    rows = run_all(seed=args.seed)
    write_findings(rows, args.out)
    print(f"wrote {len(rows)} rows to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
