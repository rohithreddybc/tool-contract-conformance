"""The sec 2 equivalence probe corpus generator -- detector_analysis_plan.md sec 2:

    "For each tool in the corpus, the probe set is:
     1. Every recorded real call captured during adapter smoke-testing.
     2. Boundary probes generated by a committed script from the tool's signature: for each
        parameter, a valid value, a type-valid but domain-invalid value, and where the type
        admits it, a zero/empty value.
     3. For each precondition clause in the tool's contract, one probe satisfying it and one
        violating it.
     The corpus is frozen with the checker. Probes are never added to justify a result."

SEPARATION FROM THE CHECKER'S OWN PROBES -- READ THIS BEFORE REUSING ANYTHING HERE.
detector_analysis_plan.md sec 4.3 depends on this corpus and the checker's own probe generation
(the not-yet-built `dynamic/probes.py`, scheduled in ARCHITECTURE-FINAL.md sec 7 for the dynamic
harness milestone) being genuinely disjoint code paths: "if the same probes both screened
equivalence and drove the checker, probe gaps would be invisible by construction" (sec 4.3). As of
this commit, `dynamic/probes.py` does not exist anywhere in this repository -- there is nothing
yet for this module to share code with, so the separation currently holds by construction, not by
discipline. That will stop being true the moment someone builds the checker-probe generator, and
whoever does so must NOT import from this module (or vice versa), even where the logic looks
identical (e.g. both might want "a boundary value per argument type"). Loud reminder, per
CLAUDE.md's instruction to say so if this line is ever blurred: **do not let this module and the
future checker-probe generator become the same code.**

This module only ever reads a `core.model.Contract` and a snapshot/candidate-args pool; it never
calls a checker function (adapters.contract_check.*) and is never called by one.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Optional

from core.model import Contract
from core.predicates import PathError, PredicateTypeError, compile_predicate, evaluate

__all__ = ["Probe", "generate_boundary_probes", "generate_precondition_probes", "build_equivalence_probe_corpus"]


@dataclass(frozen=True)
class Probe:
    """One probe call: `tool` with `args`, tagged with `origin` for provenance/reporting.
    `origin` is one of "recorded", "boundary:<param>:<subkind>" (subkind in valid/domain_invalid/
    zero_empty), or "precondition_satisfy:<clause_id>" / "precondition_violate:<clause_id>"."""

    tool: str
    args: dict
    origin: str


# ---------------------------------------------------------------------------------------------
# 1. Recorded real calls -- pass-through, kept here only so callers assemble the whole corpus
#    through one function (build_equivalence_probe_corpus) rather than three.
# ---------------------------------------------------------------------------------------------


def _recorded_probes(tool: str, recorded_calls: "list[dict]") -> list[Probe]:
    return [Probe(tool=tool, args=dict(call), origin="recorded") for call in recorded_calls]


# ---------------------------------------------------------------------------------------------
# 2. Boundary probes from the tool's declared signature.
# ---------------------------------------------------------------------------------------------

# Generic, type-only heuristics -- no benchmark or domain vocabulary. "domain_invalid" cannot be
# generic about domain semantics (that would require understanding what a valid id looks like per
# tool), so it uses a value that is syntactically well-typed but chosen to be maximally unlikely
# to name a real entity -- a sentinel string / an implausibly large number -- documented here
# rather than silently guessed at per call site.
_VALID_BY_TYPE = {"str": "probe_value", "int": 7, "float": 7.5, "bool": True}
_DOMAIN_INVALID_BY_TYPE = {"str": "__PROBE_DOMAIN_INVALID__", "int": 999_999_999, "float": 1e18, "bool": False}
_ZERO_EMPTY_BY_TYPE = {"str": "", "int": 0, "float": 0.0, "bool": False}


def generate_boundary_probes(contract: Contract) -> list[Probe]:
    """One probe per (parameter, subkind) combination declared in `contract.signature.args`,
    holding every OTHER parameter at its own valid value -- so a single probe genuinely isolates
    one argument's boundary behaviour rather than presenting several boundary values at once.
    Respects `probe_values` when the contract declares an explicit set (schema.json argSpec)."""
    args_spec = contract.signature.args
    base = {name: _VALID_BY_TYPE.get(spec.type, "probe_value") for name, spec in args_spec.items()}

    probes: list[Probe] = []
    for name, spec in args_spec.items():
        if spec.probe_values:
            for i, v in enumerate(spec.probe_values):
                probe_args = dict(base)
                probe_args[name] = v
                probes.append(Probe(tool=contract.tool, args=probe_args, origin=f"boundary:{name}:declared_{i}"))
            continue

        valid = _VALID_BY_TYPE.get(spec.type)
        domain_invalid = _DOMAIN_INVALID_BY_TYPE.get(spec.type)
        zero_empty = _ZERO_EMPTY_BY_TYPE.get(spec.type)

        for subkind, value in (("valid", valid), ("domain_invalid", domain_invalid), ("zero_empty", zero_empty)):
            if value is None and spec.type not in _VALID_BY_TYPE:
                continue  # unrecognised type -- do not guess
            probe_args = dict(base)
            probe_args[name] = value
            probes.append(Probe(tool=contract.tool, args=probe_args, origin=f"boundary:{name}:{subkind}"))

    return probes


# ---------------------------------------------------------------------------------------------
# 3. One satisfying + one violating probe per declared precondition clause.
# ---------------------------------------------------------------------------------------------


def generate_precondition_probes(contract: Contract, pre: Any, candidates: "list[dict]") -> list[Probe]:
    """For each declared precondition clause, search `candidates` (typically the union of
    recorded calls and boundary probes -- see `build_equivalence_probe_corpus`) for one args-dict
    that makes the clause's predicate evaluate True against `pre`, and one that makes it False.
    A clause with no satisfying or no violating candidate in the pool contributes only what it
    found -- never invented outright, so the corpus stays traceable to real recorded calls or
    generic boundary values, per sec 2's "probes are never added to justify a result." `result`
    is passed as `{}` -- these are PRE-call probes; the checker evaluates a precondition against
    (pre, args), never against a call's result, so no `result` binding is needed here."""
    probes: list[Probe] = []
    for pc in contract.preconditions:
        compiled = compile_predicate(pc.predicate)
        satisfying: Optional[dict] = None
        violating: Optional[dict] = None
        for cand in candidates:
            try:
                held = evaluate(compiled, pre, pre, cand, {})
            except (PathError, PredicateTypeError):
                continue
            if held and satisfying is None:
                satisfying = cand
            if not held and violating is None:
                violating = cand
            if satisfying is not None and violating is not None:
                break
        if satisfying is not None:
            probes.append(Probe(tool=contract.tool, args=dict(satisfying), origin=f"precondition_satisfy:{pc.id}"))
        if violating is not None:
            probes.append(Probe(tool=contract.tool, args=dict(violating), origin=f"precondition_violate:{pc.id}"))
    return probes


# ---------------------------------------------------------------------------------------------
# Assembly
# ---------------------------------------------------------------------------------------------


def build_equivalence_probe_corpus(
    contract: Contract, recorded_calls: "list[dict]", pre: Any
) -> list[Probe]:
    """The full sec 2 corpus for one tool: recorded calls + boundary probes + one
    satisfying/violating probe per precondition clause, in that order, with exact-duplicate
    args-dicts collapsed (keeping the first origin tag) so the corpus this function returns is
    the literal set §4.1's survival check runs, with no accidental repetition inflating it."""
    recorded = _recorded_probes(contract.tool, recorded_calls)
    boundary = generate_boundary_probes(contract)
    candidates = [p.args for p in recorded + boundary]
    precondition = generate_precondition_probes(contract, pre, candidates)

    # The same args-dict often earns more than one origin tag (a boundary probe for one
    # parameter can simultaneously be the violating witness for a precondition clause). Merge
    # tags for identical args rather than keeping only the first-seen one, so a probe's full
    # provenance stays traceable -- dropping the later tags would silently understate why a probe
    # is in the corpus, which sec 2's "probes are never added to justify a result" cuts against
    # in spirit even though it is about additions, not omissions.
    order: list[tuple] = []
    origins_by_key: dict[tuple, list[str]] = {}
    args_by_key: dict[tuple, dict] = {}
    for p in recorded + boundary + precondition:
        key = tuple(sorted(p.args.items()))
        if key not in origins_by_key:
            order.append(key)
            origins_by_key[key] = []
            args_by_key[key] = p.args
        origins_by_key[key].append(p.origin)

    return [Probe(tool=contract.tool, args=args_by_key[k], origin=";".join(origins_by_key[k])) for k in order]
